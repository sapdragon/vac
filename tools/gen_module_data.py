#!/usr/bin/env python3
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import compare_vac_worker as cmp

BLOB_SIZE = 0xFC0
HEADER = bytes.fromhex("C9B87CADC00F000039CEC08C00000000")
RSA_KEY_PREFIX = bytes.fromhex("305C300D06092A864886F70D0101010500034B003048024100")
RSA_KEY_SIZE = 94
IMPORT = re.compile(r'VAC_IMPORT\( "([^"]+)", [^,]+, (\w+),')
NEWLINE = chr(10)


def build_plain_blob() -> bytes:
    text = (ROOT / "sdk/src/bootstrap/imports.inl").read_text(encoding="utf-8")
    blob = bytearray(HEADER)
    seen_libraries = set()
    for library, function in IMPORT.findall(text):
        if library not in seen_libraries:
            seen_libraries.add(library)
            blob += library.encode() + bytes(1)
        blob += function.encode() + bytes(1)
    if len(blob) > BLOB_SIZE:
        raise ValueError("strings do not fit the blob")
    return bytes(blob) + bytes(BLOB_SIZE - len(blob))


def encrypt(key: bytes, plain: bytes) -> bytes:
    schedule = cmp.ice_schedule(key)[::-1]
    return b"".join(cmp.ice_decrypt_block(schedule, plain[i:i + 8]) for i in range(0, len(plain), 8))


def format_bytes(data: bytes) -> str:
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return ("," + NEWLINE + chr(9)).join(rows)


def main() -> int:
    folder = Path(sys.argv[1])
    image = (folder / "module.dll").read_bytes()
    packet = cmp.read_packet(folder / "inputVacPacket_ScanId_4.bin")
    node = cmp.find_single_node(cmp.PeImage(folder / "module.dll"), packet.module_id, packet.version, "original")
    config = cmp.ice_decrypt_buffer(node.ice_key[:8], packet.encrypted_payload)
    if cmp.crc32_ieee(config) != packet.crc32:
        raise ValueError("packet CRC mismatch")

    ib_rsa_key = image.find(RSA_KEY_PREFIX)
    if ib_rsa_key < 0:
        raise ValueError("RSA public key not found")
    rsa_key = image[ib_rsa_key:ib_rsa_key + RSA_KEY_SIZE]

    key = config[:8]
    plain = build_plain_blob()
    encrypted = encrypt(key, plain)
    if cmp.ice_decrypt_buffer(key, encrypted) != plain:
        raise ValueError("round trip failed")

    lines = [
        f"// Generated by tools/gen_module_data.py from {folder.name}. Do not edit.",
        "// clang-format off",
        "const vac::u8 vac::k_rgubRsaPublicKey[vac::k_cubRsaPublicKey] = {",
        chr(9) + format_bytes(rsa_key),
        "};",
        "",
        "const vac::bootstrap::BootstrapBlob_t vac::bootstrap::g_EncryptedBlob = { {",
        chr(9) + format_bytes(encrypted),
        "} };",
        "// clang-format on",
        "",
    ]
    Path(sys.argv[2]).write_text(NEWLINE.join(lines), encoding="utf-8", newline=NEWLINE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
